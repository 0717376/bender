const DICT = lang === "ru" ? RU : EN;

/** Строка интерфейса; {0}, {1}… заменяются аргументами. */
export const t = (key: Key, ...args: (string | number)[]): string =>
  DICT[key].replace(/\{(\d)\}/g, (_, i) => String(args[Number(i)] ?? ""));

// Формы: один, два-четыре, пять и больше. Английскому хватает первой и последней.
const FORMS = {
  cards: { ru: ["карточка", "карточки", "карточек"], en: ["card", "cards"] },
  notes: { ru: ["запись", "записи", "записей"], en: ["note", "notes"] },
  to_review: { ru: ["повтор", "повтора", "повторов"], en: ["review", "reviews"] },
  to_learn: { ru: ["доучивается", "доучиваются", "доучиваются"], en: ["learning", "learning"] },
  new_cards: { ru: ["новая", "новые", "новых"], en: ["new", "new"] },
  streak_days: { ru: ["день подряд", "дня подряд", "дней подряд"], en: ["day streak", "day streak"] },
  days: { ru: ["день", "дня", "дней"], en: ["day", "days"] },
} as const;

export function pluralForm(n: number): 0 | 1 | 2 {
  const a = Math.abs(n) % 100, b = a % 10;
  if (a > 10 && a < 20) return 2;
  if (b === 1) return 0;
  if (b >= 2 && b <= 4) return 1;
  return 2;
}

/** «5 карточек»; wordOnly — одно слово без числа, когда число нарисовано отдельно. */
export function plural(n: number, key: keyof typeof FORMS, wordOnly = false): string {
  const word = lang === "ru" ? FORMS[key].ru[pluralForm(n)] : FORMS[key].en[n === 1 ? 0 : 1];
  return wordOnly ? word : `${n} ${word}`;
}

/** Короткий день недели по дате YYYY-MM-DD. */
export const weekday = (isoDay: string): string => {
  const [y, m, d] = isoDay.split("-").map(Number);
  return new Date(y, m - 1, d).toLocaleDateString(locale, { weekday: "short" }).replace(".", "");
};

/** «12 окт» — подпись дня в графиках. */
export const shortDate = (isoDay: string): string => {
  const [y, m, d] = isoDay.split("-").map(Number);
  return new Date(y, m - 1, d).toLocaleDateString(locale, { day: "numeric", month: "short" }).replace(".", "");
};
