const DICT = lang === "ru" ? RU : EN;

/** Строка интерфейса; {0}, {1}… заменяются аргументами. */
export const t = (key: Key, ...args: (string | number)[]): string =>
  DICT[key].replace(/\{(\d)\}/g, (_, i) => String(args[Number(i)] ?? ""));

// Формы: один, два-четыре, пять и больше. Английскому хватает первой и последней.
const FORMS = {
  workouts: { ru: ["тренировка", "тренировки", "тренировок"], en: ["workout", "workouts"] },
  sets: { ru: ["подход", "подхода", "подходов"], en: ["set", "sets"] },
  exercises: { ru: ["упражнение", "упражнения", "упражнений"], en: ["exercise", "exercises"] },
} as const;

export function pluralForm(n: number): 0 | 1 | 2 {
  const a = Math.abs(n) % 100, b = a % 10;
  if (a > 10 && a < 20) return 2;
  if (b === 1) return 0;
  if (b >= 2 && b <= 4) return 1;
  return 2;
}

/** «5 подходов»; wordOnly — одно слово без числа, когда число нарисовано отдельно. */
export function plural(n: number, key: keyof typeof FORMS, wordOnly = false): string {
  const word = lang === "ru" ? FORMS[key].ru[pluralForm(n)] : FORMS[key].en[n === 1 ? 0 : 1];
  return wordOnly ? word : `${n} ${word}`;
}

const dateOf = (isoDay: string) => {
  const [y, m, d] = isoDay.split("-").map(Number);
  return new Date(y, m - 1, d);
};

/** Короткий день недели по дате YYYY-MM-DD. */
export const weekdayOf = (isoDay: string): string =>
  dateOf(isoDay).toLocaleDateString(locale, { weekday: "short" }).replace(".", "");

/** «12 окт» — подпись дня в графиках. */
export const shortDate = (isoDay: string): string =>
  dateOf(isoDay).toLocaleDateString(locale, { day: "numeric", month: "short" }).replace(".", "");
