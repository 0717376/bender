"""Первое наполнение стенда.

Пустая вики и пустой список задач на свежей установке выглядят как несработавшая
установка: человек не понимает, поднялось оно вообще или нет. Поэтому один раз, на
первом запуске, кладём страницу «Начало работы» и пару задач-примеров — их можно
спокойно удалить, обратно они не вернутся (метка в data/).
"""

import logging
import os

from . import config, tasks_store

logger = logging.getLogger("wiki.seed")

MARKER = os.path.join(config.DATA_DIR, ".seeded")
PAGE = "Начало работы.md"

WELCOME = """# Начало работы

Это ваш личный агент: вики, задачи и читалка книг — и один ассистент,
который умеет всё это делать за вас.

## Где что

- **Вики** — эта страница и все остальные. Обычные markdown-файлы на диске:
  можно править руками, можно попросить ассистента. Папок нет, есть страницы:
  у любой страницы могут появиться дочерние. Ссылки по имени: `[[Начало работы]]`.
- **Задачи** — в стиле Things: Входящие, Сегодня, Планы, Когда-нибудь, проекты,
  повторы, дедлайны. Пара примеров там уже лежит.
- **Книги** — читалка epub и pdf с выписками. Полка пустая: загрузите книгу,
  и с ассистентом можно будет обсуждать её по тексту, а не по пересказу.

## Как разговаривать

Чат есть в каждом интерфейсе — кнопка справа. Контекст общий: начали в вики,
продолжили в задачах, дописали из Telegram. У каждой книги разговор свой.

Что попросить для начала:

- «Заведи страницу про домашний сервер и запиши туда, что бэкапы по средам»
- «Добавь в задачи: продлить домен, дедлайн — конец месяца»
- «Каждый будний день в 8:30 присылай мне план на день»
- «Что мы обсуждали про переезд?» — журнал разговоров хранится целиком

## Дальше

- Персона ассистента живёт на странице `persona.md` — там задаётся, как он
  разговаривает и что про вас знает. Правьте её как обычную страницу.
- Долгую память, выученные навыки и запланированные задания показывает
  команда `/status` в Telegram.
- Проверить, что всё живо: `./bender doctor` в каталоге проекта.
"""

TASKS = [
    ("Осмотреться в задачах",
     "Перетащите задачу мышью, отметьте выполненной или нажмите на неё — "
     "откроются заметки, дедлайн и повтор.",
     "today"),
    ("Спросить ассистента, что он умеет",
     "Чат — кнопка справа. Или напишите боту в Telegram.",
     None),
]


def _wiki_is_empty() -> bool:
    """Пусто ли в вики. Персону не считаем: её заводит сам агент при первом ходе."""
    skip = {config.PERSONA_NAME, config.PERSONA_LEGACY}
    for root, dirs, files in os.walk(config.WIKI_DIR):
        dirs[:] = [d for d in dirs if not d.startswith(".")]
        if any(f.endswith(".md") and f not in skip for f in files):
            return False
    return True


def init() -> None:
    if os.path.exists(MARKER):
        return
    try:
        if _wiki_is_empty():
            os.makedirs(config.WIKI_DIR, exist_ok=True)
            with open(os.path.join(config.WIKI_DIR, PAGE), "w", encoding="utf-8") as f:
                f.write(WELCOME)
            logger.info("Seed: страница «%s» заведена", PAGE)
        if not tasks_store.list_tasks(view="inbox") and not tasks_store.list_tasks(view="today"):
            for title, notes, when in TASKS:
                tasks_store.create_task(title=title, notes=notes, when=when)
            logger.info("Seed: задачи-примеры заведены")
        with open(MARKER, "w", encoding="utf-8") as f:
            f.write("Метка первого наполнения: примеры больше не заводятся.\n")
    except Exception as e:  # наполнение — не повод не подняться
        logger.warning("Seed: пропускаем, %s", e)
